# --------------------------------------------------------------------- helpers
def tex(value: object) -> str:
    text = str(value)
    for old, new in (
        ("\\", r"\textbackslash{}"),
        ("&", r"\&"),
        ("%", r"\%"),
        ("$", r"\$"),
        ("#", r"\#"),
        ("_", r"\_"),
        ("{", r"\{"),
        ("}", r"\}"),
        ("~", r"\textasciitilde{}"),
        ("^", r"\textasciicircum{}"),
    ):
        text = text.replace(old, new)
    return text


def breakable_tt(name: str) -> str:
    """Typewriter name that may break after underscores and hyphens and before inner capitals or digits."""
    text = tex(name).replace(r"\_", r"\_\allowbreak{}").replace("-", r"-\allowbreak{}")
    text = re.sub(r"(?<=[a-z])(?=[A-Z0-9])", r"\\allowbreak{}", text)
    return r"\texttt{" + text + "}"


def read_csv(path: Path) -> list[dict]:
    if not path.is_file():
        return []
    with path.open(encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def num(value: str | None) -> float | None:
    if value in (None, "", "None", "nan", "n/a"):
        return None
    if value in ("True", "False"):
        return 1.0 if value == "True" else 0.0
    return float(value)


def mean(values: list[float | None]) -> float | None:
    clean = [v for v in values if v is not None]
    return sum(clean) / len(clean) if clean else None


def f2(value: float | None) -> str:
    return "--" if value is None else f"{value:.2f}"


def pct(value: float | None) -> str:
    return "--" if value is None else f"{100 * value:.0f}"


def pct_small(value: float | None) -> str:
    """Percentage with one decimal below 1%, so that a rate such as 0.49% does not print as 0."""
    if value is None:
        return "--"
    value = float(value)
    return f"{100 * value:.1f}" if value < 0.01 else pct(value)


def thousands(value: object) -> str:
    return "--" if value is None else f"{int(value):,}".replace(",", "{,}")


def write(out_dir: Path, name: str, body: str) -> None:
    (out_dir / name).write_text(
        "% Generated by benchmark/cslaw/appendix_tables.py; do not edit by hand.\n" + body + "\n", encoding="utf-8"
    )
    print(f"wrote {out_dir / name}")


def longtable(columns: str, header: str, rows: list[str], caption: str, label: str, size: str = r"\footnotesize") -> str:
    lines = [
        "{" + size,
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{longtable}{" + columns + "}",
        r"\caption{" + caption + r"}\label{" + label + r"}\\",
        r"\toprule",
        header + r" \\",
        r"\midrule",
        r"\endfirsthead",
        r"\toprule",
        header + r" \\",
        r"\midrule",
        r"\endhead",
        r"\bottomrule",
        r"\endfoot",
    ]
    lines += rows
    lines += [r"\end{longtable}", "}"]
    return "\n".join(lines)


def simple_table(caption: str, label: str, columns: str, header: list[str], rows: list[str],
                 size: str = r"\footnotesize") -> str:
    return "\n".join(
        [r"\begin{table}[h]", r"\caption{" + caption + "}", r"\label{" + label + "}", size,
         r"\begin{tabular}{" + columns + "}", r"\toprule", *header, r"\midrule", *rows, r"\bottomrule",
         r"\end{tabular}", r"\end{table}"]
    )


def parse_denial_summary(path: Path) -> dict:
    """{(dataset or '__pooled__', explainer): (share approval-favouring, top approval-favouring, produced rate)}."""
    out: dict = {}
    if not path.is_file():
        return out
    scope = None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("## By explainer"):
            scope = "__pooled__"
        elif line.startswith("### "):
            scope = line[4:].strip()
        elif line.startswith("|") and scope and not line.startswith("|---") and not line.startswith("| explainer"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) >= 8:
                def p(cell: str) -> float | None:
                    return None if cell in ("n/a", "") else float(cell.rstrip("%")) / 100

                out[(scope, cells[0])] = (p(cells[4]), p(cells[5]), p(cells[7]))
    return out


def model_direction(payload: dict) -> dict:
    """{(dataset, explainer): {"all": [0/1 per reason], "first": [0/1 per notice]}}, 1 = favors approval by the model."""
    out: dict = defaultdict(lambda: {"all": [], "first": []})
    for row, instance in common.iter_instances(payload):
        reasons = sorted((instance.get("canonical_explanation") or {}).get("principal_reasons") or [], key=lambda r: r.get("rank", 0))[:4]
        values = (instance.get("native_contributions") or {}).get("values") or {}
        for position, reason in enumerate(reasons):
            feats = [f for f in reason.get("supporting_features") or [] if f in values]
            if not feats:
                continue
            flag = 1.0 if sum(values[f] for f in feats) / len(feats) < 0 else 0.0
            key = (row["dataset_id"], row["explainer_id"])
            out[key]["all"].append(flag)
            if position == 0:
                out[key]["first"].append(flag)
    return out


def load_optional(path: Path) -> dict:
    return common.load_results(path / "results.json") if (path / "results.json").is_file() else {}


def pooled_direction(directions: dict, explainer: str, datasets: set | None = None) -> tuple:
    flags = [f for (d, e), v in directions.items() if e == explainer and (datasets is None or d in datasets) for f in v["all"]]
    firsts = [f for (d, e), v in directions.items() if e == explainer and (datasets is None or d in datasets) for f in v["first"]]
    return mean(flags), mean(firsts)


