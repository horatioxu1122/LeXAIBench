def models_table(bundles: dict, out_dir: Path) -> None:
    seen = {}
    for payload in bundles.values():
        for row in payload.get("summary", []):
            seen.setdefault((row["dataset_id"], row["track"], row["model_id"]), row)
    rows = []
    for dataset_id, label in DATASETS:
        for track in ("primary", "audit"):
            for model_id, model_label in MODELS:
                row = seen.get((dataset_id, track, model_id))
                if row:
                    rows.append(
                        f"{tex(label)} & {TRACK_LABEL[track]} & {model_label} & {thousands(row.get('train_rows'))} "
                        f"& {thousands(row.get('test_rows'))} & {f2(row.get('model_roc_auc'))} "
                        f"& {pct_small(row.get('model_predicted_positive_rate'))} \\\\"
                    )
    write(out_dir, "tab_models.tex", longtable(
        "@{}lllrrrr@{}",
        r"Dataset & Version & Model & Training rows & Evaluation rows & ROC AUC & Denied (\%)",
        rows,
        "Accuracy and denial rate of every model on its evaluation set. A model denies when its predicted probability of the "
        "adverse outcome is at least 0.5.",
        "tab:app-models",
    ))


# Render-time edits to the taxonomy's legal_basis text. feature_taxonomy_v2.json itself stays unchanged: the result
# bundles record its SHA-256 and denial_reasons.py stops on a mismatch. The DCJS clause was a placeholder without a
# verified citation, so it gives way to a note that the correctability label is practical judgment. @SECRULES@ becomes a reference to the section that discusses bureau scores.
LEGAL_BASIS_EDITS = (
    ("; DCJS criminal-history record review (citation to be confirmed)", "; the correctability label is practical judgment"),
    (
        "(a failed qualifying score is an insufficient reason)",
        "(failing the qualifying score of the creditor's own system is an insufficient reason; whether naming a bureau "
        "score used as an input is specific enough is open, @SECRULES@)",
    ),
    ("(credit-score disclosure)", "(disclosure of the credit score)"),
    ("(inputs to the FFIEC-derived category)", "(inputs to the category the FFIEC derives)"),
)
MONTHS = ("january", "february", "march", "april", "may", "june", "july", "august", "september", "october", "november",
          "december")
PRINCIPAL_REASON_CODE = {"High": "H", "Medium": "M", "Low": "L"}
NUMBER_WORDS = {2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight", 9: "nine", 10: "ten",
                11: "eleven", 12: "twelve"}


def plain_meaning(spec: dict) -> str:
    """The taxonomy's plain meaning in words, with FDA and month names capitalized."""
    text = str(spec.get("plain_meaning", "")).replace("_", " ")
    text = re.sub(r"\bfda\b", "FDA", text)
    return re.sub(r"\b(" + "|".join(MONTHS) + r")(?= \d{4}\b)", lambda m: m.group(1).capitalize(), text)


def legal_basis(spec: dict) -> str:
    text = str(spec.get("legal_basis", ""))
    for old, new in LEGAL_BASIS_EDITS:
        text = text.replace(old, new)
    if "to be confirmed" in text:
        sys.exit(f"unresolved placeholder in the taxonomy's legal basis: {text}")
    return tex(text).replace("@SECRULES@", r"Section~\ref{sec:lessons-rules}")


def taxonomy_table(repo_root: Path, out_dir: Path) -> None:
    raw = json.loads((repo_root / "benchmark" / "metadata" / "feature_taxonomy_v2.json").read_text(encoding="utf-8"))
    rows = []
    for dataset_id, label in DATASETS:
        features = (raw["datasets"].get(dataset_id) or {}).get("features") or {}
        if not features:
            continue
        rows.append(r"\midrule \multicolumn{8}{@{}l}{\textbf{" + tex(label) + r"}} \\")
        for name, spec in features.items():
            reason = str(spec.get("principal_reason", ""))
            rows.append(
                f"{breakable_tt(name)} & {tex(plain_meaning(spec))} & {tex(spec.get('sensitivity', ''))} "
                f"& {tex(spec.get('mutability', ''))} & {tex(spec.get('verifiability', ''))} & {tex(spec.get('correctability', ''))} "
                f"& {tex(PRINCIPAL_REASON_CODE.get(reason, reason))} & {legal_basis(spec)} \\\\"
            )
    write(out_dir, "tab_taxonomy.tex", longtable(
        r"@{}>{\raggedright\arraybackslash}p{2.6cm}>{\raggedright\arraybackslash}p{2.6cm}ccccc>{\raggedright\arraybackslash}p{5.0cm}@{}",
        r"Feature & Plain meaning & S & M & V & C & R & Legal basis",
        rows,
        "Feature taxonomy. S: sensitivity (S protected characteristic, P possible proxy or socially sensitive attribute, "
        "N neither). M: mutability (M mutable at low cost, PS over the short or medium term, PL over the long term, P set jointly "
        "with the institution, I immutable, N not actionable). V and C: whether the person can verify and correct the value "
        "(Y yes, P only through institutional or third party records or at the institution's discretion, N no). R: suitability "
        "as a principal reason (H high, M medium, L low). Reg B: Regulation B. Reg C: Regulation C, which implements HMDA. "
        "Reg Z: Regulation Z. ECOA: Equal Credit Opportunity Act. FCRA: Fair Credit Reporting Act. FCBA: Fair Credit Billing "
        "Act. FHA: Fair Housing Act. FD\\&C Act: Federal Food, Drug, and Cosmetic Act. FFIEC: Federal Financial Institutions "
        "Examination Council.",
        "tab:app-taxonomy",
        size=r"\scriptsize",
    ))


def results_by_dataset(analysis: Path, denial_dir: Path, sources: dict, out_dir: Path) -> None:
    e1 = {}
    for name in ("credit", "noncredit", "nullbaselines"):
        e1.update(parse_denial_summary(denial_dir / name / "denial_reasons_summary.md"))
    before: dict = {}
    after: dict = {}
    for name in ("credit", "noncredit", "nullbaselines"):
        before.update(model_direction(sources.get(name) or {}))
        after.update(model_direction(load_optional(denial_dir / name)))
    e2: dict = defaultdict(lambda: defaultdict(list))
    for sub in ("regb_credit", "regb_nullbaselines", "regb_noncredit"):
        for row in read_csv(analysis / sub / "regb_reference_instances.csv"):
            key = (row["dataset_id"], row["explainer_id"])
            for metric in ("pr_overlap_m1_grouped", "pr_top1_m1_grouped", "pr_outside_m1_grouped"):
                e2[key][metric].append(num(row.get(metric)))
    e3: dict = defaultdict(list)
    for row in read_csv(analysis / "specificity" / "specificity_configs.csv"):
        if row["bundle"] in ("credit", "nullbaselines", "noncredit"):
            e3[(row["dataset_id"], row["explainer_id"])].append(float(row["mean_pairwise_jaccard"]))
    e6 = {
        (row["dataset_id"], row["explainer_id"]): float(row["mean"])
        for row in read_csv(analysis / "specificity" / "recourse_by_dataset.csv")
    }
    rows = []
    for dataset_id, label in DATASETS:
        rows.append(r"\midrule \multicolumn{10}{@{}l}{\textbf{" + tex(label) + r"}} \\")
        for method, method_label in METHODS:
            own = e1.get((dataset_id, method))
            cov = e2.get((dataset_id, method), {})
            spec = e3.get((dataset_id, method))
            if not own and not cov and not spec:
                continue
            b = before.get((dataset_id, method), {})
            a = after.get((dataset_id, method), {})
            rows.append(
                f"{method_label} & {pct(mean(b.get('all', [])))} & {pct(mean(b.get('first', [])))} & {pct(mean(a.get('all', [])))} "
                f"& {pct(own[2]) if own else '--'} "
                f"& {f2(mean(cov.get('pr_overlap_m1_grouped', [])))} & {pct(mean(cov.get('pr_top1_m1_grouped', [])))} "
                f"& {pct(mean(cov.get('pr_outside_m1_grouped', [])))} & {f2(mean(spec) if spec else None)} "
                f"& {pct(e6.get((dataset_id, method)))} \\\\"
            )
    write(out_dir, "tab_results_by_dataset.tex", longtable(
        "@{}lrrrrrrrrr@{}",
        r"Notice & E1 bef. & E1 first & E1 aft. & Expl. & E2 marg. & E2 first & E2 out. & E3 & E6",
        rows,
        "Results by dataset, pooled over models and versions. E1 bef.: percentage of the up to four reasons built from the method's "
        "ranking whose model contribution favors approval; E1 first: the same for the first reason; E1 aft.: the same after the "
        "direction rule. Expl.: percentage of applicants left with at least one reason after the rule. E2 marg.: share of the marginal applicant method's four reasons that the notice names. E2 first: percentage of "
        "applicants with the same first reason. E2 out.: percentage of the notice's reasons outside the method's four. E3: mean "
        "overlap of reason sets between applicants under the same model. E6: percentage of applicants with at least one valid change.",
        "tab:app-results-dataset",
    ))


def results_by_model(analysis: Path, out_dir: Path) -> None:
    rows = []
    sources = (("Consumer credit", ("regb_credit", "regb_nullbaselines")), ("HMDA and outside credit", ("regb_noncredit",)))
    for label, subs in sources:
        cells: dict = defaultdict(dict)
        for sub in subs:
            for row in read_csv(analysis / sub / "regb_reference_pooled_by_model.csv"):
                cells[(row["model_id"], row["explainer_id"])][row["metric"]] = row
        rows.append(r"\midrule \multicolumn{6}{@{}l}{\textbf{" + label + r"}} \\")
        for model_id, model_label in MODELS:
            for method in REAL + ("global_ranking", "random_reasons"):
                stats = cells.get((model_id, method))
                if not stats:
                    continue

                def ci(metric: str, stats: dict = stats) -> str:
                    row = stats.get(metric)
                    if not row:
                        return "--"
                    return f"{float(row['mean']):.2f} [{float(row['ci_low']):.2f}, {float(row['ci_high']):.2f}]"

                rows.append(
                    f"{model_label} & {METHOD_LABEL[method]} & {ci('pr_overlap_m1_grouped')} & {ci('pr_overlap_m2_grouped')} "
                    f"& {ci('pr_top1_m1_grouped')} & {ci('pr_outside_m1_grouped')} \\\\"
                )
    write(out_dir, "tab_results_by_model.tex", longtable(
        "@{}llrrrr@{}",
        r"Model & Notice & Marginal method & Average method & First reason & Outside",
        rows,
        "Agreement of each notice with the two commentary methods by model, with 95\\% bootstrap intervals. Marginal and average "
        "method: share of that method's four reasons that the notice names. First reason: share of applicants whose first reasons "
        "match (marginal method). Outside: share of the notice's reasons outside the marginal method's four.",
        "tab:app-results-model",
        size=r"\scriptsize",
    ))


def k_sweep(analysis: Path, out_dir: Path) -> None:
    coverage: dict = {}
    agreement: dict = {}
    for k in (2, 3, 4, 5):
        base = analysis / "regb_credit" if k == 4 else analysis / "sweep_k" / f"regb_k{k}"
        groups: dict = defaultdict(list)
        for row in read_csv(base / "regb_reference_instances.csv"):
            groups[row["explainer_id"]].append(num(row.get("pr_overlap_m1_grouped")))
        for method, values in groups.items():
            coverage[(k, method)] = mean(values)
        for row in read_csv(base / "regb_m1_vs_m2.csv"):
            if row["level"] == "pooled_by_model":
                agreement[(k, row["model_id"], row["metric"])] = float(row["mean"])
    ks = (2, 3, 4, 5)
    rows = [f"{METHOD_LABEL[m]} & " + " & ".join(f2(coverage.get((k, m))) for k in ks) + r" \\" for m in REAL]
    rows.append(r"\midrule")
    rows += [
        f"Reasons in common, {label.lower()} & " + " & ".join(f2(agreement.get((k, m, "m1_m2_overlap"))) for k in ks) + r" \\"
        for m, label in MODELS
    ]
    rows += [
        f"Same first reason (\\%), {label.lower()} & " + " & ".join(pct(agreement.get((k, m, "m1_m2_top1"))) for k in ks) + r" \\"
        for m, label in MODELS
    ]
    write(out_dir, "tab_k_sweep.tex", simple_table(
        r"Number of reasons $k$. Top: share of the marginal applicant method's $k$ reasons that each notice names (consumer credit, "
        r"pooled). Bottom: share of one commentary method's $k$ reasons that the other also names, and the percentage of applicants for whom they give the same "
        r"first reason, by model.",
        "tab:app-k", "@{}lrrrr@{}", [r"& $k=2$ & $k=3$ & $k=4$ & $k=5$ \\"], rows,
    ))


def band_sweep(analysis: Path, out_dir: Path) -> None:
    pooled: dict = defaultdict(list)
    for row in read_csv(analysis / "band_sweep" / "band_sweep_rows.csv"):
        pooled[(row["model_id"], float(row["band"]), int(row["min_rows"]))].append(row)
    rows = []
    for model_id, model_label in MODELS:
        for _model, band, min_rows in sorted(k for k in pooled if k[0] == model_id):
            items = pooled[(model_id, band, min_rows)]

            def avg(field: str, items: list = items) -> float | None:
                return mean([num(item.get(field)) for item in items])

            rows.append(
                f"{model_label} & {band:.2f} & {min_rows} & {avg('reference_rows'):.0f} & {f2(avg('overlap_vs_baseline'))} "
                f"& {pct(avg('top1_same_as_baseline'))} & {pct(avg('top1_same_as_average_method'))} & "
                + " & ".join(f2(avg(f"overlap_{m}")) for m in REAL) + r" \\"
            )
    write(out_dir, "tab_band_sweep.tex", longtable(
        "@{}lrrrrrrrrrrr@{}",
        r"Model & Band & Min. & Ref. rows & In common & Same first (\%) & Same as avg. (\%) & SHAP & LIME & DiCE & Anchors & Wachter",
        rows,
        "Reference population of the marginal applicant method (consumer credit, models refit). Band: distance below the cutoff, "
        "in the predicted probability of the adverse outcome, within which approved applicants count as marginal. Min.: minimum "
        "number of approved applicants. Ref. rows: mean size of the reference group. "
        "In common: share of the baseline's four reasons (band 0.10, at least 200) that the setting also selects. Same first: "
        "applicants whose first reason matches the baseline's. Same as avg.: applicants "
        "whose first reason matches the average applicant method's. The last five columns give each method's share of the marginal "
        "applicant method's four reasons, counted by factor, so that each monthly field of the Default Credit data counts as its "
        "own factor. Each cell averages the eight combinations of dataset and version. The baseline row therefore differs from "
        "Table~\\ref{tab:app-results-model}, which counts a monthly history as one reason and pools applicants.",
        "tab:app-band",
        size=r"\scriptsize",
    ))


def lime_sampling(analysis: Path, denial_dir: Path, sources: dict, out_dir: Path) -> None:
    """LIME's main runs against the robustness runs: sampling around the applicant (lime_local) and, when present,
    the library's default discretized mode (lime_default)."""
    runs = [("credit", "regb_credit", "Main runs"), ("lime_local", "regb_lime_local", "Around the applicant")]
    if (denial_dir / "lime_default" / "results.json").is_file():
        runs.append(("lime_default", "regb_lime_default", "Discretized"))
    marked = {name: parse_denial_summary(denial_dir / name / "denial_reasons_summary.md").get(("__pooled__", "lime"))
              for name, _sub, _label in runs}
    before = {name: pooled_direction(model_direction(sources.get(name) or {}), "lime") for name, _sub, _label in runs}
    after = {name: pooled_direction(model_direction(load_optional(denial_dir / name)), "lime") for name, _sub, _label in runs}

    def coverage(sub: str, model_id: str) -> float | None:
        path = analysis / sub / "regb_reference_instances.csv"
        if not path.is_file():
            return None
        return mean([num(r.get("pr_overlap_m1_grouped")) for r in read_csv(path)
                     if r["explainer_id"] == "lime" and r["model_id"] == model_id])

    spec = {row["bundle"]: float(row["mean"]) for row in read_csv(analysis / "specificity" / "specificity_pooled.csv")
            if row["explainer_id"] == "lime"}

    def line(label: str, cells: list[str]) -> str:
        return label + " & " + " & ".join(cells) + r" \\"

    rows = [
        line(r"Reasons marked by LIME as favoring approval (\%)",
             [pct(marked[n][0] if marked[n] else None) for n, _s, _l in runs]),
        line(r"Reasons favoring approval by the model, before the rule (\%)", [pct(before[n][0]) for n, _s, _l in runs]),
        line(r"First reasons favoring approval by the model, before the rule (\%)",
             [pct(before[n][1]) for n, _s, _l in runs]),
        line(r"Reasons favoring approval by the model, after the rule (\%)", [pct(after[n][0]) for n, _s, _l in runs]),
    ]
