def feature_labels(*payloads: dict) -> dict:
    labels: dict = {}
    pattern = re.compile(r" (contributed to the denial|supported approval)$")
    for payload in payloads:
        for _row, instance in common.iter_instances(payload):
            for reason in (instance.get("canonical_explanation") or {}).get("principal_reasons") or []:
                feats = reason.get("supporting_features") or []
                if len(feats) == 1:
                    labels.setdefault(feats[0], pattern.sub("", reason.get("reason_text", feats[0])))
    return labels


def wrap_table(paragraph: str, columns: str, header: str, items: list[str]) -> str:
    return "\n".join(
        [paragraph, r"\begin{center}\footnotesize", r"\begin{tabular}{" + columns + "}", r"\toprule", header + r" \\",
         r"\midrule", *items, r"\bottomrule", r"\end{tabular}", r"\end{center}"]
    )


def worked_notices(denial_dir: Path, source: dict, out_dir: Path) -> None:
    shared = common.load_results(denial_dir / "shared" / "results.json")
    credit = common.load_results(denial_dir / "credit" / "results.json")
    nulls = common.load_results(denial_dir / "nullbaselines" / "results.json")
    labels = feature_labels(source, shared, credit, nulls)
    parts = []

    # (a) Direction, before the rule (HELOC, primary version). (a1) SHAP's first reason is a factor whose model
    # contribution favored approval. (a2) LIME labels factors as favoring approval although the model's
    # contributions count them against the applicant.
    def pick(explainer: str, accept) -> tuple:
        rows_by_model = {
            row["model_id"]: row
            for row in source.get("summary", [])
            if (row["dataset_id"], row["track"], row["explainer_id"]) == ("heloc", "primary", explainer)
        }
        for model_id, _label in MODELS:
            row = rows_by_model.get(model_id) or {}
            for instance in sorted(row.get("instance_results") or [], key=lambda i: common.eval_row_index(i) or 0):
                reasons = sorted((instance.get("canonical_explanation") or {}).get("principal_reasons") or [], key=lambda r: r.get("rank", 0))[:4]
                values = (instance.get("native_contributions") or {}).get("values") or {}
                contribs = [mean([values.get(f) for f in r.get("supporting_features") or [] if f in values]) for r in reasons]
                if reasons and accept(reasons, contribs):
                    return instance, model_id, reasons, contribs
        return None, None, None, None

    def direction_table(title: str, text: str, picked: tuple) -> str | None:
        instance, model_id, reasons, contribs = picked
        if instance is None:
            return None
        items = [
            f"{r.get('rank')} & {tex(r.get('reason_text', ''))} & {'--' if c is None else f'{c:+.2f}'} \\\\"
            for r, c in zip(reasons, contribs)
        ]
        return wrap_table(
            r"\paragraph{" + title + "} " + text + " (HELOC, " + MODEL_LABEL[model_id].lower() + ", primary version, row "
            + str(common.eval_row_index(instance)) + f", probability of denial {float(instance.get('prediction_score', 0)):.2f}). "
            r"The notice is shown as worded before the direction rule. The last column gives the model's own "
            r"contribution of each factor to the log odds of denial; a negative value means the factor favored approval.",
            "@{}rlr@{}", r"Rank & Reason as worded & Contribution", items,
        )

    shap_case = pick(
        "shap",
        lambda reasons, contribs: reasons[0].get("signed_direction") == "decreases_denial" and contribs[0] is not None and contribs[0] < 0,
    )
    lime_case = pick(
        "lime",
        lambda reasons, contribs: reasons[0].get("signed_direction") == "decreases_denial" and contribs[0] is not None and contribs[0] > 0,
    )
    for part in (
        direction_table("A first reason that helped the applicant.", "SHAP's notice for a denied applicant lists first a factor that favored approval", shap_case),
        direction_table(
            "Signs that contradict the model.",
            "LIME's notice, which takes each sign from the slope of LIME's local linear surrogate, marks factors as favoring "
            "approval that the model counts against the applicant",
            lime_case,
        ),
    ):
        if part:
            parts.append(part)

    # (b) Reasons repeated across applicants: the consumer credit configuration with the highest LIME overlap across
    # applicants (the first in bundle order when several tie).
    best = None
    scores = []
    for row in credit.get("summary", []):
        if row["explainer_id"] != "lime":
            continue
        sets = [frozenset(common.principal_reason_features(i.get("canonical_explanation"), 4)[:4]) for i in row.get("instance_results") or []]
        sets = [s for s in sets if s]
        pairs = [len(a & b) / len(a | b) for a, b in itertools.combinations(sets, 2)]
        if pairs:
            scores.append((sum(pairs) / len(pairs), row))
            if best is None or sum(pairs) / len(pairs) > best[0]:
                best = (sum(pairs) / len(pairs), row)
    if best:
        score, row = best
        key = (row["dataset_id"], row["track"], row["model_id"])
        tied = [r for s, r in scores if abs(s - score) < 1e-12]
        tied_datasets = {r["dataset_id"] for r in tied}
        dataset_label = tex(DATASET_LABEL.get(key[0], key[0]))
        setting = TRACK_LABEL[key[1]].lower() + " version, " + MODEL_LABEL[key[2]].lower() + f"; mean overlap {score:.2f}"
        if score > 1 - 1e-12:
            title = "The same reasons for every applicant."
            where = "in which LIME gives every applicant the same reasons"
        else:
            title = "Reasons repeated across applicants."
            where = "in which LIME's notices overlap most across applicants"
        if len(tied) == 1:
            place = f"the {dataset_label} configuration {where} ({setting})"
        elif len(tied_datasets) == 1:
            place = f"one of the {NUMBER_WORDS.get(len(tied), str(len(tied)))} {dataset_label} configurations {where} ({setting})"
        else:
            place = (f"one of the {NUMBER_WORDS.get(len(tied), str(len(tied)))} consumer credit configurations {where} "
                     f"({dataset_label}, {setting})")
        groups = common.cslaw_section(credit).get("groups") or {}
        means = (((groups.get(common.cslaw_group_key(*key)) or {}).get("regb_reference") or {}).get("near_cutoff") or {}).get("means") or {}
        canned = None
        for nrow in nulls.get("summary", []):
            if (nrow["dataset_id"], nrow["track"], nrow["model_id"], nrow["explainer_id"]) == key + ("global_ranking",):
                first = (nrow.get("instance_results") or [None])[0]
                if first:
                    canned = common.principal_reason_features(first.get("canonical_explanation"), 4)[:4]
        items = []
        for instance in sorted(row.get("instance_results") or [], key=lambda i: common.eval_row_index(i) or 0)[:5]:
            lime = common.principal_reason_features(instance.get("canonical_explanation"), 4)[:4]
            values = (instance.get("native_contributions") or {}).get("values") or {}
            m1 = common.top_adverse_features(values, 4, means) if values and means else []
            items.append(
                f"{common.eval_row_index(instance)} & {tex('; '.join(labels.get(f, f) for f in lime))} "
                f"& {tex('; '.join(labels.get(f, f) for f in m1))} \\\\"
            )
        if canned:
            items += [r"\midrule", f"Canned & {tex('; '.join(labels.get(f, f) for f in canned))} & \\\\"]
        parts.append(wrap_table(
            r"\paragraph{" + title + "} LIME's notices for the first five explained applicants in " + place + ", beside the "
            r"marginal applicant method's reasons for the same applicants and the canned notice for that model. Reasons are listed by "
            r"factor, after the direction rule.",
            r"@{}r>{\raggedright\arraybackslash}p{5.6cm}>{\raggedright\arraybackslash}p{5.6cm}@{}",
            r"Row & LIME notice & Marginal applicant method", items,
        ))

    # (c) Model choice: the HELOC applicant of Table 2 (row 198, primary), with reasons in words.
    groups = common.cslaw_section(shared).get("groups") or {}
    per_model: dict = defaultdict(dict)
    for row, instance in common.iter_instances(shared):
        if (row["dataset_id"], row["track"]) != ("heloc", "primary") or common.eval_row_index(instance) != 198:
            continue
        per_model[row["model_id"]][row["explainer_id"]] = common.principal_reason_features(instance.get("canonical_explanation"), 4)[:4]
        values = (instance.get("native_contributions") or {}).get("values")
        if values:
            means = groups[common.cslaw_group_key("heloc", "primary", row["model_id"])]["regb_reference"]["near_cutoff"]["means"]
            per_model[row["model_id"]]["regb_reference"] = common.top_adverse_features(values, 4, means)
    items = []
    for model_id, model_label in MODELS:
        for method in ("regb_reference", "shap", "lime"):
            feats = per_model.get(model_id, {}).get(method)
            if feats:
                items.append(f"{model_label} & {METHOD_LABEL[method]} & {tex('; '.join(labels.get(f, f) for f in feats))} \\\\")
        items.append(r"\midrule")
    if items:
        parts.append(wrap_table(
            r"\paragraph{Model choice.} The HELOC applicant of Table~\ref{tab:worked} (row 198, primary version), with the reasons "
            r"written out for the marginal applicant method, SHAP, and LIME under each model.",
            r"@{}ll>{\raggedright\arraybackslash}p{8.4cm}@{}", r"Model & Notice & Reasons in order", items[:-1],
        ))
    write(out_dir, "worked_notices.tex", "\n\n".join(parts))


